function cutoffHash(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

function calcCutoff(answers) {
  // answers = [{ type: "F", flag: 2 }, ...] 12개
  const keys = Object.keys(CUTOFF_TYPES);
  const totals = {};
  keys.forEach(k => totals[k] = 0);
  let flagSum = 0;
  answers.forEach(a => { if (a && totals[a.type] !== undefined) { totals[a.type] += 1; flagSum += a.flag || 0; } });

  const maxFlag = CUTOFF_QUESTIONS.reduce((s, q) => s + Math.max(...q.choices.map(c => c.flag)), 0);
  const minFlag = CUTOFF_QUESTIONS.reduce((s, q) => s + Math.min(...q.choices.map(c => c.flag)), 0);
  const score = Math.round(((flagSum - minFlag) / (maxFlag - minFlag)) * 100);
  const level = cutoffLevel(score);

  const seed = answers.map(a => a && a.type).join("");
  const n = answers.length || 1;
  const percentages = {};
  keys.forEach(k => percentages[k] = Math.round((totals[k] / n) * 100));
  const sorted = keys.slice().sort((a, b) => totals[b] !== totals[a] ? totals[b] - totals[a] : cutoffHash(a + seed) - cutoffHash(b + seed));
  const primary = sorted[0], secondary = sorted[1];

  return {
    totals, percentages, sorted, primary, secondary,
    primaryInfo: CUTOFF_TYPES[primary], secondaryInfo: CUTOFF_TYPES[secondary],
    score, level, flagSum, maxFlag, minFlag,
    comboNote: getCutoffCombo(primary, secondary),
    matchInfo: CUTOFF_TYPES[CUTOFF_TYPES[primary].match]
  };
}

