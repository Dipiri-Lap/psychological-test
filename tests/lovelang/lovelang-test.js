function getComboNote(typeA, typeB) {
  if (typeA === typeB) return null;
  const key = [typeA, typeB].sort().join("_");
  return LOVELANG_COMBO_NOTES[key];
}

// ============================================
// 채점 함수
// ============================================

function calcLoveLang(answers) {
  // answers = ["W", "T", "G", "S", "P", ...] 15개 (각 문항에서 선택한 type)
  const totals = { W: 0, T: 0, G: 0, S: 0, P: 0 };

  answers.forEach(type => {
    if (totals[type] !== undefined) totals[type] += 1;
  });

  const maxScore = LOVELANG_QUESTIONS.length; // 문항 수
  const percentages = {};
  Object.keys(totals).forEach(key => {
    percentages[key] = Math.round((totals[key] / maxScore) * 100);
  });

  // 점수 내림차순 정렬
  const sorted = Object.entries(totals).sort((a, b) => b[1] - a[1]);
  const primaryType = sorted[0][0];
  const secondaryType = sorted[1][0];
  const isTie = sorted[0][1] === sorted[1][1]; // 1위, 2위 동점 여부 (혼합형 강조용)

  return {
    totals,
    percentages,
    maxScore,
    primaryType,
    primaryTypeInfo: LOVELANG_TYPES[primaryType],
    secondaryType,
    secondaryTypeInfo: LOVELANG_TYPES[secondaryType],
    comboNote: getComboNote(primaryType, secondaryType),
    isTie
  };
}

