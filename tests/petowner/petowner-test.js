function getPetOwnerComboNote(a, b) {
  if (a === b) return null;
  return PETOWNER_COMBO_NOTES[[a, b].sort().join("_")] || null;
}

// ============================================
// 채점 함수
// ============================================

function calcPetOwner(answers) {
  // answers = ["C", "P", "K", ...] 18개 (선택한 type, 응답 순서대로)
  const types = Object.keys(PETOWNER_TYPES);
  const totals = {};
  types.forEach(t => totals[t] = 0);
  const firstIdx = {};
  answers.forEach((t, i) => {
    if (totals[t] === undefined) return;
    totals[t] += 1;
    if (firstIdx[t] === undefined) firstIdx[t] = i;
  });

  const maxScore = PETOWNER_QUESTIONS.length;
  const answered = answers.length || 1;
  const percentages = {};
  types.forEach(t => percentages[t] = Math.round((totals[t] / answered) * 100));

  // 점수 내림차순, 동점이면 먼저 고른 유형 우선
  const sorted = types.slice().sort((a, b) => {
    if (totals[b] !== totals[a]) return totals[b] - totals[a];
    return (firstIdx[a] ?? 999) - (firstIdx[b] ?? 999);
  });
  const primaryType = sorted[0], secondaryType = sorted[1];
  const gap = totals[primaryType] - totals[secondaryType];

  return {
    totals, percentages, maxScore,
    sorted,
    primaryType, primaryTypeInfo: PETOWNER_TYPES[primaryType],
    secondaryType, secondaryTypeInfo: PETOWNER_TYPES[secondaryType],
    gap,
    isBlend: gap <= 1,                                   // 1~2위가 거의 비슷하면 혼합형으로 안내
    comboNote: getPetOwnerComboNote(primaryType, secondaryType),
    matchInfo: PETOWNER_TYPES[PETOWNER_TYPES[primaryType].match]
  };
}

